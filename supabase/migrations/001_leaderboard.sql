create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_id uuid not null references auth.users (id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 16),
  score integer not null check (score >= 0),
  level integer not null check (level between 1 and 10),
  lines integer not null check (lines >= 0),
  stage_id text not null default 'fresh',
  start_level integer not null default 1 check (start_level between 1 and 10),
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists scores_ranking_idx
  on public.scores (score desc, level desc, created_at asc);

alter table public.scores enable row level security;

create policy "Anyone can read leaderboard scores"
  on public.scores
  for select
  to anon, authenticated
  using (true);

create policy "Players can submit their own scores"
  on public.scores
  for insert
  to authenticated
  with check (auth.uid() = player_id);
